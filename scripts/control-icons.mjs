import * as icons from '@hugeicons/core-free-icons';
import { writeFileSync } from 'node:fs';

// Bundle only the Hugeicons used by our plain-JavaScript extension.
const names = {
  play: 'PlayIcon', pause: 'PauseIcon', next: 'NextIcon', previous: 'PreviousIcon',
  shuffle: 'ShuffleIcon', queue: 'Queue01Icon', lyrics: 'Mic01Icon',
  more: 'MoreHorizontalIcon', add: 'Add01Icon', close: 'Cancel01Icon', calendar: 'Calendar03Icon',
  repeat: 'RepeatIcon', repeatOne: 'RepeatOne01Icon', volume: 'VolumeHighIcon', muted: 'VolumeMute01Icon', fullscreen: 'FullScreenIcon', follow: 'FocusPointIcon',
  back: 'ArrowLeft01Icon', refresh: 'RefreshIcon', folder: 'Folder01Icon', chevron: 'ArrowRight01Icon'
};
const data = Object.fromEntries(Object.entries(names).map(([name, exported]) => [
  name, icons[exported].map(([tag, attributes]) => [tag,
    Object.fromEntries(Object.entries(attributes).filter(([key]) => key !== 'key'))])
]));
writeFileSync('extension/control-icons.js', `// Generated by scripts/control-icons.mjs from @hugeicons/core-free-icons (MIT).
// https://github.com/hugeicons/hugeicons
(() => {
  'use strict';
  const data = ${JSON.stringify(data)};
  const ns = 'http://www.w3.org/2000/svg';
  function create(name) {
    const svg = document.createElementNS(ns, 'svg');
    for (const [key, value] of Object.entries({ viewBox: '0 0 24 24', width: '24', height: '24', fill: 'none', 'aria-hidden': 'true', focusable: 'false' })) svg.setAttribute(key, value);
    svg.classList.add('sf-icon');
    for (const [tag, attributes] of data[name]) {
      const shape = document.createElementNS(ns, tag);
      for (const [key, value] of Object.entries(attributes)) shape.setAttribute(key.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase()), value);
      svg.append(shape);
    }
    return svg;
  }
  function set(element, name, label) {
    element.replaceChildren(create(name));
    element.classList.add('sf-icon-button');
    element.setAttribute('aria-label', label);
    element.dataset.sfTooltip = label;
    element.removeAttribute('title');
    return element;
  }
  globalThis.FocusedIcons = { create, set };
})();
`);
